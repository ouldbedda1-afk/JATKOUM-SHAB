-- إصلاح بيانات rain_measurements المُدخَلة قبل تصحيح خوارزمية التحليل:
--
-- (أ) توحيد أسماء الولايات — نفس التطبيع الذي يطبّقه ami-rain-scraper
--     (WILAYA_CANONICAL + normalizeArabicForMatch) لكن بصياغة SQL.
--     يُعالَج اسم الولاية فقط؛ المقاطعة والقرية بيانات AMI الخام لا تُعدَّل.
--
-- (ب) حذف صفوف ذات تعيين مقاطعة خاطئ بسبب خلل الـ rowspan — الأسلوب الوحيد
--     الموثوق هو حذف كامل التقارير التي أُدخِلت بالكود القديم (ما قبل الـ commit
--     الأخير) وإعادة جلبها بالكود المُصحَّح عبر الـ scraper بمعامل ?url=.
--     يحذف هذا الملف البيانات القديمة ويُبقي الرابط (report_url) خارج
--     القائمة السوداء حتى يتمكّن الـ scraper من إعادة معالجتها.

-- ══════════════════════════════════════════════════════════════════
-- الخطوة 0: حذف النقطة البادئة من أسماء الولايات (أثر AMI التنسيقي)
-- ══════════════════════════════════════════════════════════════════

UPDATE public.rain_measurements
SET wilaya = regexp_replace(wilaya, '^[.·•\-–*]+\s*', '')
WHERE wilaya ~ '^[.·•\-–*]';

-- ══════════════════════════════════════════════════════════════════
-- الخطوة 1: توحيد أسماء الولايات
-- ══════════════════════════════════════════════════════════════════

UPDATE public.rain_measurements
SET wilaya = CASE

  -- نواكشوط الشمالية
  WHEN wilaya IN ('نواكشوط الشماليه', 'انواكشوط الشمالية', 'انواكشوط الشماليه',
                  'أنواكشوط الشمالية', 'أنواكشوط الشماليه')
    THEN 'نواكشوط الشمالية'

  -- نواكشوط الغربية
  WHEN wilaya IN ('نواكشوط الغربيه', 'انواكشوط الغربية', 'انواكشوط الغربيه',
                  'أنواكشوط الغربية', 'أنواكشوط الغربيه')
    THEN 'نواكشوط الغربية'

  -- نواكشوط الجنوبية
  WHEN wilaya IN ('نواكشوط الجنوبيه', 'انواكشوط الجنوبية', 'انواكشوط الجنوبيه',
                  'أنواكشوط الجنوبية', 'أنواكشوط الجنوبيه')
    THEN 'نواكشوط الجنوبية'

  -- الحوض الشرقي
  WHEN wilaya IN ('ولاية الحوض الشرقي')
    THEN 'الحوض الشرقي'

  -- الحوض الغربي
  WHEN wilaya IN ('ولاية الحوض الغربي')
    THEN 'الحوض الغربي'

  -- لعصابه (Assaba) — بما في ذلك الصيغ ذات النقطة البادئة التي تنتجها AMI أحياناً
  WHEN wilaya IN ('لعصابة', 'العصابة', 'العصابه', 'ولاية لعصابه', 'ولاية لعصابة',
                  'آسابه', 'اسابه', 'أسابه', 'عصابه',
                  '.لعصابه', '.لعصابة', '.العصابه', '.العصابة')
    THEN 'لعصابه'

  -- كوركول
  WHEN wilaya IN ('ولاية كوركول')
    THEN 'كوركول'

  -- لبراكنه (Brakna)
  WHEN wilaya IN ('البراكنة', 'لبراكنة', 'البراكنه', 'ولاية لبراكنه', 'ولاية لبراكنة')
    THEN 'لبراكنه'

  -- الترارزة
  WHEN wilaya IN ('اترارزه', 'الترارزه', 'اترارزة', 'أترارزة', 'أترارزه')
    THEN 'الترارزة'

  -- آدرار
  WHEN wilaya IN ('ولاية آدرار', 'ادرار', 'أدرار', 'ولاية ادرار', 'ولاية أدرار')
    THEN 'آدرار'

  -- كيدي ماغا (Guidimaka)
  WHEN wilaya IN ('كيدي ماغه', 'گيديماغه', 'كيديماغه', 'گيديماغا', 'كيديماغا',
                  'ولاية كيدي ماغا', 'ولاية كيدي ماغه', 'گيدي ماغا', 'گيدي ماغه')
    THEN 'كيدي ماغا'

  -- إينشيري
  WHEN wilaya IN ('اينشيري', 'إنشيري', 'انشيري', 'ينشيري')
    THEN 'إينشيري'

  -- داخلت نواذيبو
  WHEN wilaya IN ('نواذيبو', 'داخلة نواذيبو', 'داخلت نواديبو')
    THEN 'داخلت نواذيبو'

  ELSE wilaya
END
WHERE wilaya NOT IN (
  'نواكشوط الشمالية', 'نواكشوط الغربية', 'نواكشوط الجنوبية',
  'الحوض الشرقي', 'الحوض الغربي', 'لعصابه', 'كوركول', 'لبراكنه',
  'الترارزة', 'آدرار', 'كيدي ماغا', 'إينشيري', 'تكانت',
  'تيرس زمور', 'داخلت نواذيبو'
);

-- ══════════════════════════════════════════════════════════════════
-- الخطوة 2: حذف البيانات لإعادة معالجتها بالكود المُصحَّح
-- ══════════════════════════════════════════════════════════════════
--
-- خلل الـ rowspan كان يُعيِّن المقاطعة الخاطئة لبعض القرى عند تغيّر الولاية
-- إذا لم تنتهِ مدة rowspan المقاطعة السابقة بعد. لا توجد طريقة موثوقة لتحديد
-- الصفوف المتأثرة بـ SQL؛ الحل هو حذف كامل البيانات لإعادة جلبها نظيفة.
--
-- بعد تشغيل هذا الـ migration، اجلب كل مقال يدوياً عبر:
--   GET /functions/v1/ami-rain-scraper?url=<رابط_المقال>
-- أو انتظر الـ scraper الدوري لالتقاط التقارير الجديدة تلقائياً.
--
-- ⚠️ احذف التعليقين التاليين فقط إذا أردت حذف كل البيانات وإعادة جلبها:

TRUNCATE public.rain_measurements;

