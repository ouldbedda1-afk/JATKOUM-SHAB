// المقاطع أدناه منقولة من مقالات حقيقية في أرشيف ami.mr (رقم المقال في كل اختبار)
function parse(html, title = '') {
  const $ = cheerio.load(`<div id="root">${html}</div>`);
  return parseRainReport($, $('#root'), title);
}
const flat = (res) => res.rows.map((r) => `${r.wilaya}|${r.moughataa}|${r.village}|${r.mm}`);

