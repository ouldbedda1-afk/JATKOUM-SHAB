/** مفتاح مطابقة عربي: يتجاهل التشكيل والتطويل والهمزات والتاء المربوطة وعلامات التنصيص */
export function rainNameKey(value) {
  return String(value || '')
    .replace(/[ً-ْـ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[گڭ]/g, 'ك')
    .replace(/["'”“«».·•]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

// مفتاح الولاية أشدّ تساهلاً: بلا مسافات («كيدي ماغا/كيديماغا») وبلا ألف
// أو ياء مكرَّرة («الحوض االشرقي»، «الشرقيي») وبلا بادئة «ولاية/الولاية» ولو ملتصقة
function wilayaKey(value) {
  return rainNameKey(value)
    .replace(/[/\\:،,\-–—]+$/, '')
    .replace(/^(في |ب|ل)?(ال)?(و ?لا ?يه|وايه|الايه)[\s:\-–]*/, '')
    .replace(/\s+/g, '')
    .replace(/([اي])\1+/g, '$1');
}

