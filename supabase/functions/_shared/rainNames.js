/** { wilaya, name } للمقاطعة المعروفة، أو null (تُزال بادئة «مقاطعة» إن وُجدت) */
export function knownMoughataa(value) {
  const key = rainNameKey(value).replace(/^(في |ب)?مقاطعه\s+/, '');
  return MOUGHATAA_INDEX[key] || null;
}
