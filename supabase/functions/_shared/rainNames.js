const WILAYA_INDEX = {};
WILAYA_VARIANTS.forEach((variants) => {
  variants.forEach((v) => {
    WILAYA_INDEX[wilayaKey(v)] = variants[0];
    // AMI يكتب «انواكشوط» و«نواكشوط» للولايات الثلاث
    if (v.startsWith('نواكشوط')) WILAYA_INDEX[wilayaKey(`ا${v}`)] = variants[0];
  });
});

export const CANONICAL_WILAYAS = WILAYA_VARIANTS.map((v) => v[0]);

/** الاسم المعتمد للولاية، أو null إن لم يكن الاسم ولاية معروفة (لا تخمين) */
export function canonicalWilaya(value) {
  return WILAYA_INDEX[wilayaKey(value)] || null;
}

/** كل الولايات المذكورة في نص حرّ (عنوان/مقدمة تقرير)، بلا تكرار */
export function wilayasMentionedIn(text) {
  const haystack = wilayaKey(text);
  const hits = new Set();
  // الأطول أولاً حتى لا تُحتسب «نواذيبو» داخل «داخلت نواذيبو» مرتين، ولا «الحوض» بلا تحديد
  Object.keys(WILAYA_INDEX).sort((a, b) => b.length - a.length).forEach((key) => {
    // «نواكشوط» وحدها تَرِد في كل مقال كمكان صدور الخبر («اليوم في انواكشوط»)، لا كولاية القراءات
    if (WILAYA_INDEX[key] === 'نواكشوط') return;
    if (key.length >= 5 && haystack.includes(key)) hits.add(WILAYA_INDEX[key]);
  });
  return [...hits];
}

